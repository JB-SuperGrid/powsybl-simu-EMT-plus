/**
 * The script as written, without PSCAD: what it builds, against the layout the {@code .pscx} writer writes, and that Python
 * takes it.
 *
 * @author Jean-Baptiste Heyberger : jean-baptiste.heyberger@supergrid-institute.com
 */
class PscadPythonScriptWriterTest {

    private static final PscadSimulationSettings SETTINGS = new PscadSimulationSettings(50.0e-6, 0.5, 50.0, PscadEdition.PROFESSIONAL);

    @Test
    void theScriptPlacesEveryComponentOfTheLayoutWhereThePscxHasIt(@TempDir Path tempDir) throws IOException {
        Network network = ExampleNetworks.withLoadFlow(ExampleNetworks.createTwoBusNetworkWithIdealInfiniteBusGenerator());

        PscadFileWriter.PscadProject project = PscadFileWriter.write(network, tempDir, SETTINGS, List.of(), PscadPythonScriptWriter.INSTANCE);

        assertThat(project.file()).isEqualTo(tempDir.resolve("two_bus.py"));
        assertThat(tempDir.resolve("two_bus.pscx")).doesNotExist();
        String script = Files.readString(project.file());
        List<PscadDrawing.Placed> placed = PscadDrawing.of(project.circuit()).elements().stream()
                .filter(PscadDrawing.Placed.class::isInstance).map(PscadDrawing.Placed.class::cast).toList();
        Matcher calls = Pattern.compile("(?m)^    place\\(canvas, \"([^\"]+)\", (\\d+), (\\d+), ").matcher(script);
        int i = 0;
        while (calls.find()) {
            PscadDrawing.Placed expected = placed.get(i++);
            assertThat(calls.group(1)).isEqualTo(expected.definition());
            assertThat(Integer.parseInt(calls.group(2))).isEqualTo(expected.x());
            assertThat(Integer.parseInt(calls.group(3))).isEqualTo(expected.y());
        }
        assertThat(i).isEqualTo(placed.size());
        // Parameters as PSCAD's form holds them, past the library's codec: a choice by its index - the source's single-line view.
        assertThat(script).contains("place(canvas, \"master:source3\", ").contains("\"Ctrl\": \"0\"").contains("\"View\": \"1\"")
                .contains("component._parameters(None, -1, {name: value for name, value in parameters.items() if name in known})")
                .contains("\"Name\": \"V_B1_A\", \"Group\": \"Bus voltages\"");
    }

    @Test
    void aRunFromRestRecordsEveryStepWithPscadsOwnSwitching(@TempDir Path tempDir) throws IOException {
        Network network = ExampleNetworks.withLoadFlow(ExampleNetworks.createTwoBusNetworkWithIdealInfiniteBusGenerator());

        String script = Files.readString(PscadFileWriter.write(network, tempDir, SETTINGS, List.of(), PscadPythonScriptWriter.INSTANCE).file());

        assertThat(script).contains("NAME = \"two_bus\"").contains("PAGE_SIZE = 0")
                .contains("\"time_duration\": 0.5,").contains("\"time_step\": 50.0,").contains("\"sample_step\": 50.0,")
                .contains("\"StartType\": \"STANDARD\",").contains("\"SnapType\": \"NONE\",").doesNotContain("startup_filename")
                .contains("\"interpolate_switching\": True,").contains("\"detect_chatter\": True,").contains("\"remove_chatter\": True,")
                .contains("\"description\": \"Generated by SimuEmt for network 'two-bus'\",");
    }

    @Test
    void aRestartStartsFromItsSnapshotAndATemplateWritesOne() {
        PscadSimulationSettings onTimeStep = new PscadSimulationSettings(20.0e-6, 0.3, 50.0, PscadEdition.PROFESSIONAL, PscadSwitching.ON_TIME_STEP);
        PscadDrawing drawing = PscadDrawing.of(com.powsybl.simuemt.pscad.PscadCircuitBuilder.build(
                ExampleNetworks.withLoadFlow(ExampleNetworks.createTwoBusNetworkWithIdealInfiniteBusGenerator()), onTimeStep));

        String restart = PscadPythonScriptWriter.script(drawing, onTimeStep, new PscadRun(0.3, "C:/work/restart/two_bus_steady.snp", 0.0), "r");
        String template = PscadPythonScriptWriter.script(drawing, onTimeStep, new PscadRun(0.04, null, 0.02), "t");

        assertThat(restart).contains("\"StartType\": \"FROM_SNAP_FILE\",").contains("\"startup_filename\": \"C:/work/restart/two_bus_steady.snp\",")
                .contains("\"SnapType\": \"NONE\",").contains("\"time_step\": 20.0,")
                .contains("\"interpolate_switching\": False,").contains("\"detect_chatter\": False,").contains("\"remove_chatter\": False,");
        assertThat(template).contains("\"StartType\": \"STANDARD\",").contains("\"SnapType\": \"ONLY_ONCE\",").contains("\"SnapTime\": 0.02,")
                .contains("\"time_duration\": 0.04,");
    }

    @Test
    void aTransmissionLineIsCreatedFromItsDefinitionThenDrawnBetweenItsNodes(@TempDir Path tempDir) throws IOException {
        Network network = ExampleNetworks.createTwoBusNetworkWithIdealInfiniteBusGenerator();
        network.getLine("L1_2").addExtension(BergeronLineModel.class, new BergeronLineModel(320.0, 3.3e-4));
        ExampleNetworks.withLoadFlow(network);

        String script = Files.readString(PscadFileWriter.write(network, tempDir, SETTINGS, List.of(), PscadPythonScriptWriter.INSTANCE).file());

        assertThat(script).contains("    (\"L1_2\", (\n        \"    <Definition classid=\\\"RowDefn\\\" name=\\\"L1_2\\\"")
                .contains("<param name=\\\"type\\\" value=\\\"TLine\\\" />")
                .containsPattern("    transmission_line\\(canvas, \"two_bus:L1_2\", \\d+, \\d+, 144, \\{\"Name\": \"L1_2\"");
    }

    @Test
    void aFortranComponentIsCreatedFromItsDefinition(@TempDir Path tempDir) throws IOException {
        Network network = ExampleNetworks.withLoadFlow(ExampleNetworks.createWindTurbineNetwork());

        String script = Files.readString(PscadFileWriter.write(network, tempDir, SETTINGS, List.of(), PscadPythonScriptWriter.INSTANCE).file());

        assertThat(script).contains("    (\"WT1_CTRL\", (\n").contains("classid=\\\"UserCmpDefn\\\" name=\\\"WT1_CTRL\\\"")
                .contains("<segment name=\\\"Fortran\\\"").contains("place(canvas, \"wind_turbine:WT1_CTRL\", ");
    }

    @Test
    void stringsAreWrittenAsPythonTakesThem() {
        assertThat(PscadPythonScriptWriter.literal("a\"b\\c\nd\te")).isEqualTo("\"a\\\"b\\\\c\\nd\\te\"");
        assertThat(PscadPythonScriptWriter.literal("\u0001é")).isEqualTo("\"\\x01é\"");
        assertThat(PscadPythonScriptWriter.number(5.0e-5)).isEqualTo("5.0E-5");
    }

    /** Python compiles every script: the two-bus bench, a line of its own, a wind turbine's Fortran. */
    @Test
    void pythonCompilesTheScripts(@TempDir Path tempDir) throws Exception {
        assumeTrue(pythonAvailable(), "no Python on this machine");
        Network line = ExampleNetworks.createTwoBusNetworkWithIdealInfiniteBusGenerator();
        line.getLine("L1_2").addExtension(BergeronLineModel.class, new BergeronLineModel(320.0, 3.3e-4));
        for (Network network : List.of(ExampleNetworks.createTwoBusNetworkWithIdealInfiniteBusGenerator(), line,
                ExampleNetworks.createWindTurbineNetwork())) {
            Path directory = Files.createDirectories(tempDir.resolve(network.getId()));
            Path script = PscadFileWriter.write(ExampleNetworks.withLoadFlow(network), directory, SETTINGS, List.of(),
                    PscadPythonScriptWriter.INSTANCE).file();
            Process process = new ProcessBuilder("py", "-I", "-m", "py_compile", script.toString()).redirectErrorStream(true).start();
            String output = new String(process.getInputStream().readAllBytes(), StandardCharsets.ISO_8859_1);
            assertThat(process.waitFor(60, TimeUnit.SECONDS)).isTrue();
            assertThat(process.exitValue()).as("py_compile %s: %s", script, output).isZero();
        }
    }

    private static boolean pythonAvailable() {
        try {
            Process process = new ProcessBuilder("py", "--version").redirectErrorStream(true).start();
            process.getInputStream().readAllBytes();
            return process.waitFor(30, TimeUnit.SECONDS) && process.exitValue() == 0;
        } catch (IOException e) {
            return false;
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
            return false;
        }
    }
}
